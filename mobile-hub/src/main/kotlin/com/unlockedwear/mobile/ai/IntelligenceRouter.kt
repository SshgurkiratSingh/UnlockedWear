package com.unlockedwear.mobile.ai

import com.unlockedwear.protocol.BiometricSnapshot
import com.unlockedwear.protocol.DailyBriefing
import com.unlockedwear.protocol.IntelligenceRequest
import com.unlockedwear.protocol.WeatherState
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Sealed hierarchy defining requests dispatched across UnlockedWear AI models.
 */
sealed class AiRequest {
    /**
     * Analytical inquiry or optimization task routed to DeepSeek-Chat.
     */
    data class DeepSeekAnalysis(
        val query: String,
        val context: BiometricSnapshot? = null
    ) : AiRequest()

    /**
     * Full nocturnal intelligence synthesis and morning briefing routed to DeepSeek.
     */
    data class DeepSeekBriefing(
        val request: IntelligenceRequest
    ) : AiRequest()

    /**
     * Interactive natural language query or voice command routed to Gemini.
     */
    data class GeminiInteractive(
        val query: String
    ) : AiRequest()

    /**
     * Contextual real-time insight synthesis combining telemetry and weather routed to Gemini.
     */
    data class GeminiContextual(
        val biometrics: BiometricSnapshot,
        val weather: WeatherState
    ) : AiRequest()
}

/**
 * Sealed hierarchy defining responses produced by the AI routing infrastructure.
 */
sealed class AiResponse {
    /**
     * Structured daily briefing generated by DeepSeek.
     */
    data class Briefing(val briefing: DailyBriefing) : AiResponse()

    /**
     * Textual conversational response or insight generated by an AI model.
     *
     * @property text The generated response string.
     * @property engine The identifier of the AI model that produced this response.
     */
    data class Text(val text: String, val engine: String) : AiResponse()

    /**
     * Indicates a failure occurred during dispatch or inference execution.
     */
    data class Error(val message: String, val cause: Throwable? = null) : AiResponse()
}

/**
 * Intelligence router directing cognitive workloads to the optimal AI model:
 * - DeepSeek: Analytical telemetry synthesis, scheduled briefings, mathematical optimization, recovery modeling.
 * - Gemini: Interactive queries, voice prompts, dynamic situational multimodal insights.
 */
@Singleton
class IntelligenceRouter @Inject constructor(
    private val deepSeekClient: DeepSeekClient,
    private val geminiClient: GeminiClient
) {
    /**
     * Dispatches an [AiRequest] to the appropriate intelligence engine and returns a typed [AiResponse].
     *
     * @param request The request to execute.
     * @return [AiResponse] reflecting the inference outcome.
     */
    suspend fun routeRequest(request: AiRequest): AiResponse {
        return when (request) {
            is AiRequest.DeepSeekBriefing -> {
                deepSeekClient.requestMorningBriefing(request.request)
                    .fold(
                        onSuccess = { AiResponse.Briefing(it) },
                        onFailure = { AiResponse.Error("DeepSeek briefing synthesis failed: ${it.message}", it) }
                    )
            }

            is AiRequest.DeepSeekAnalysis -> {
                deepSeekClient.requestOnDemandAnalysis(request.query, request.context)
                    .fold(
                        onSuccess = { AiResponse.Text(text = it, engine = "DeepSeek-Chat") },
                        onFailure = { AiResponse.Error("DeepSeek analysis failed: ${it.message}", it) }
                    )
            }

            is AiRequest.GeminiInteractive -> {
                geminiClient.askGemini(request.query)
                    .fold(
                        onSuccess = { AiResponse.Text(text = it, engine = "Gemini 1.5 Flash") },
                        onFailure = { AiResponse.Error("Gemini interactive query failed: ${it.message}", it) }
                    )
            }

            is AiRequest.GeminiContextual -> {
                geminiClient.generateContextualInsight(request.biometrics, request.weather)
                    .fold(
                        onSuccess = { AiResponse.Text(text = it, engine = "Gemini 1.5 Flash") },
                        onFailure = { AiResponse.Error("Gemini contextual insight failed: ${it.message}", it) }
                    )
            }
        }
    }
}
