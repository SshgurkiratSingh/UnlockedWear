package com.unlockedwear.mobile.ai

import com.google.ai.client.generativeai.GenerativeModel
import com.google.ai.client.generativeai.type.content
import com.google.ai.client.generativeai.type.generationConfig
import com.unlockedwear.mobile.data.AppPreferences
import com.unlockedwear.protocol.BiometricSnapshot
import com.unlockedwear.protocol.WeatherState
import kotlinx.coroutines.flow.first
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Official Google AI Client SDK (com.google.ai.client.generativeai) implementation for Gemini models.
 *
 * Dedicated to real-time interactive user queries, conversational assistant interactions,
 * and multimodal contextual situational insights on the Galaxy S25 companion hub.
 */
@Singleton
class GeminiClient @Inject constructor(
    private val appPreferences: AppPreferences
) {
    companion object {
        const val MODEL_NAME = "gemini-1.5-flash"
    }

    /**
     * Resolves the configured API key and instantiates the official [GenerativeModel].
     */
    private suspend fun getGenerativeModel(systemInstruction: String? = null): GenerativeModel {
        val apiKey = appPreferences.geminiApiKey.first()
        if (apiKey.isBlank()) {
            throw IllegalStateException("Gemini API key is not configured in Settings.")
        }
        return GenerativeModel(
            modelName = MODEL_NAME,
            apiKey = apiKey,
            generationConfig = generationConfig {
                temperature = 0.7f
            },
            systemInstruction = systemInstruction?.let {
                content { text(it) }
            }
        )
    }

    /**
     * Executes a conversational interactive query using Google's official Generative AI SDK.
     *
     * @param query The natural language command or user query.
     * @return [Result] containing Gemini's response text.
     */
    suspend fun askGemini(query: String): Result<String> {
        return try {
            val model = getGenerativeModel(
                systemInstruction = "You are the UnlockedWear voice assistant and co-pilot on Galaxy S25 companion hub. Assist the user with actionable, concise advice."
            )
            val response = model.generateContent(query)
            val text = response.text?.trim() ?: "No response generated by Gemini."
            Result.success(text)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    /**
     * Generates a concise contextual insight combining current live biometrics and ambient weather.
     *
     * @param biometrics The latest [BiometricSnapshot].
     * @param weather The current [WeatherState].
     * @return [Result] containing situational guidance string.
     */
    suspend fun generateContextualInsight(
        biometrics: BiometricSnapshot,
        weather: WeatherState
    ): Result<String> {
        return try {
            val model = getGenerativeModel(
                systemInstruction = "You are ORBIT X, an aerospace biometric and environmental co-pilot. Synthesize physiological telemetry and ambient weather into 1-2 concise, actionable sentences."
            )

            val prompt = """
                Contextual Intelligence Telemetry:
                - Heart Rate: ${biometrics.heartRateBpm} BPM
                - HRV RMSSD: ${biometrics.hrvRmssdMs} ms
                - SpO2: ${biometrics.spo2Percent}%
                - Skin Temp: ${biometrics.skinTempCelsius} °C (Ambient: ${biometrics.ambientTempCelsius} °C, Z-Score: ${biometrics.thermalZScore})
                - Ambient Weather: ${weather.tempCelsius} °C, ${weather.condition}, UV Index: ${weather.uvIndex} (Peak: ${weather.forecastMaxUvi})
                
                Provide a 1-2 sentence real-time physiological and environmental recommendation.
            """.trimIndent()

            val response = model.generateContent(prompt)
            val text = response.text?.trim() ?: "Normal telemetry verified."
            Result.success(text)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
