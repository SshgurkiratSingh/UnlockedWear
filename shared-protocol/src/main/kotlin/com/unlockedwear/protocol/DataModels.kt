package com.unlockedwear.protocol

import kotlinx.serialization.Serializable

/**
 * Status indicator for thermal sensor acquisition accuracy and contact state.
 */
object ThermalSensorStatus {
    /** Status is uninitialized or uncalibrated. */
    const val STATUS_UNKNOWN = 0

    /** Valid thermal acquisition with normal confidence. */
    const val STATUS_VALID = 1

    /** Watch thermal sensor is in poor contact or moving (reduced accuracy). */
    const val STATUS_ACCURACY_LOW = 2

    /** Watch thermal sensor has optimal skin contact and stable baseline. */
    const val STATUS_ACCURACY_HIGH = 3

    /** Watch is off-body / not worn. */
    const val STATUS_OFF_BODY = 4
}

/**
 * Represents a single thermal telemetry reading captured by the watch wrist sensor.
 *
 * @property skinTempCelsius Raw skin surface temperature in degrees Celsius measured at the wrist.
 * @property ambientTempCelsius Ambient air temperature in degrees Celsius (from on-device thermal sensor or weather reference).
 * @property compensatedTempCelsius Environmentally compensated skin temperature in degrees Celsius.
 * @property timestampMs Epoch timestamp in milliseconds when the reading was sampled.
 * @property status Status code reflecting sensor contact and measurement fidelity (see [ThermalSensorStatus]).
 */
@Serializable
data class ThermalFrame(
    val skinTempCelsius: Float,
    val ambientTempCelsius: Float,
    val compensatedTempCelsius: Float,
    val timestampMs: Long = System.currentTimeMillis(),
    val status: Int = ThermalSensorStatus.STATUS_VALID
) {
    /** Whether this frame represents a usable reading on a worn device. */
    val isValid: Boolean
        get() = status != ThermalSensorStatus.STATUS_OFF_BODY && status != ThermalSensorStatus.STATUS_UNKNOWN
}

/**
 * Aggregated biometric snapshot capturing real-time physiological indicators.
 *
 * Used for watch face gauge rendering, daily recovery evaluation, and AI Co-Pilot synthesis.
 *
 * @property heartRateBpm Instantaneous or short-term heart rate in beats per minute.
 * @property hrvRmssdMs Root Mean Square of Successive Differences (RMSSD) in milliseconds reflecting parasympathetic vagal tone.
 * @property spo2Percent Blood oxygen saturation percentage (0 - 100%).
 * @property skinTempCelsius Measured raw wrist skin temperature in degrees Celsius.
 * @property ambientTempCelsius Ambient air temperature in degrees Celsius.
 * @property thermalZScore Standardized z-score representing the standard deviations of skin temp from user baseline.
 * @property timestampMs Epoch timestamp in milliseconds when this snapshot was assembled.
 */
@Serializable
data class BiometricSnapshot(
    val heartRateBpm: Double,
    val hrvRmssdMs: Double,
    val spo2Percent: Int,
    val skinTempCelsius: Float,
    val ambientTempCelsius: Float,
    val thermalZScore: Double,
    val timestampMs: Long = System.currentTimeMillis()
) {
    /**
     * Convenience secondary constructor accepting [Float] heart rate.
     */
    constructor(
        heartRateBpm: Float,
        hrvRmssdMs: Double,
        spo2Percent: Int,
        skinTempCelsius: Float,
        ambientTempCelsius: Float,
        thermalZScore: Double,
        timestampMs: Long = System.currentTimeMillis()
    ) : this(
        heartRateBpm = heartRateBpm.toDouble(),
        hrvRmssdMs = hrvRmssdMs,
        spo2Percent = spo2Percent,
        skinTempCelsius = skinTempCelsius,
        ambientTempCelsius = ambientTempCelsius,
        thermalZScore = thermalZScore,
        timestampMs = timestampMs
    )
}

/**
 * Synthesized daily intelligence briefing delivered to the watch face and mobile hub.
 *
 * Generated by the AI reasoning engine (DeepSeek / Gemini) based on nocturnal biometrics,
 * environmental conditions, and pending workload queues.
 *
 * @property ringRecommendedMode Recommended bezel ring mode to display for the current user context.
 * @property coPilotHeadline Concise AI headline designed for curved watch-face text display (maximum 38 characters).
 * @property priorityTaskId Unique identifier of the primary task recommended for immediate focus, if any.
 * @property recommendedFocusBlocksMin Suggested duration of upcoming cognitive focus blocks in minutes.
 * @property thermalRecoveryAssessment Textual assessment of nocturnal autonomic and thermal recovery.
 * @property alerts Actionable real-time advisory strings (e.g. "UV index peaking in 45m; apply sunscreen").
 */
@Serializable
data class DailyBriefing(
    val ringRecommendedMode: RingMode,
    val coPilotHeadline: String,
    val priorityTaskId: String? = null,
    val recommendedFocusBlocksMin: Int,
    val thermalRecoveryAssessment: String,
    val alerts: List<String> = emptyList()
) {
    /**
     * Watch-face safe headline truncated to 38 characters if necessary.
     */
    val displayHeadline: String
        get() = if (coPilotHeadline.length <= 38) {
            coPilotHeadline
        } else {
            coPilotHeadline.take(35) + "..."
        }
}

/**
 * Environmental meteorological context synchronized between phone and watch.
 *
 * @property tempCelsius Current ambient temperature in degrees Celsius.
 * @property humidity Relative ambient humidity percentage (0 - 100%).
 * @property uvIndex Real-time Erythemal UV Index.
 * @property condition Textual weather summary (e.g., "Sunny", "Overcast", "Light Rain").
 * @property forecastMaxUvi Maximum forecasted UV Index for the day.
 * @property peakUvWindow Human-readable time window for peak solar radiation (e.g., "11:30 AM - 2:30 PM").
 * @property barometricTrendHpa 3-hour atmospheric pressure change in hectopascals (hPa).
 */
@Serializable
data class WeatherState(
    val tempCelsius: Float,
    val humidity: Float,
    val uvIndex: Float,
    val condition: String,
    val forecastMaxUvi: Float,
    val peakUvWindow: String,
    val barometricTrendHpa: Float
) {
    /**
     * Convenience secondary constructor accepting integer humidity percentage.
     */
    constructor(
        tempCelsius: Float,
        humidity: Int,
        uvIndex: Float,
        condition: String,
        forecastMaxUvi: Float,
        peakUvWindow: String,
        barometricTrendHpa: Float
    ) : this(
        tempCelsius = tempCelsius,
        humidity = humidity.toFloat(),
        uvIndex = uvIndex,
        condition = condition,
        forecastMaxUvi = forecastMaxUvi,
        peakUvWindow = peakUvWindow,
        barometricTrendHpa = barometricTrendHpa
    )

    /**
     * The evaluated WHO [UvRiskLevel] for current [uvIndex].
     */
    val currentRiskLevel: UvRiskLevel
        get() = uvRiskLevel(uvIndex)

    /**
     * The evaluated WHO [UvRiskLevel] for [forecastMaxUvi].
     */
    val peakRiskLevel: UvRiskLevel
        get() = uvRiskLevel(forecastMaxUvi)
}

/**
 * A scheduled task or activity item evaluated by the co-pilot workload engine.
 *
 * @property id Unique persistent identifier for the task.
 * @property title Concise task description or title.
 * @property deadlineHrs Estimated hours remaining until the task deadline.
 * @property cognitiveLoad The mental exertion required to execute the task.
 */
@Serializable
data class TaskItem(
    val id: String,
    val title: String,
    val deadlineHrs: Double,
    val cognitiveLoad: CognitiveLoad = CognitiveLoad.MEDIUM
) {
    /**
     * Convenience secondary constructor accepting float deadline in hours.
     */
    constructor(
        id: String,
        title: String,
        deadlineHrs: Float,
        cognitiveLoad: CognitiveLoad = CognitiveLoad.MEDIUM
    ) : this(
        id = id,
        title = title,
        deadlineHrs = deadlineHrs.toDouble(),
        cognitiveLoad = cognitiveLoad
    )
}

/**
 * Enum identifying the trigger type for an AI intelligence request.
 */
@Serializable
enum class IntelligenceRequestType {
    /** Morning wake-up synthesis evaluating nocturnal recovery, sleep baseline, and day plan. */
    MORNING_BRIEFING,

    /** On-demand contextual query or mid-day status check. */
    ON_DEMAND_ANALYSIS
}

/**
 * Payload sent to AI reasoning engines (DeepSeek / Gemini) to synthesize insights and briefings.
 *
 * Combines real-time biometrics, local weather context, and the user's impending workload queue.
 *
 * @property biometricTelemetry Current aggregated biometric snapshot.
 * @property environmentalContext Current weather, UV, and barometric state.
 * @property workloadQueue Current queue of pending tasks awaiting scheduling and execution.
 * @property requestType Type of intelligence synthesis requested.
 */
@Serializable
data class IntelligenceRequest(
    val biometricTelemetry: BiometricSnapshot,
    val environmentalContext: WeatherState,
    val workloadQueue: List<TaskItem> = emptyList(),
    val requestType: IntelligenceRequestType = IntelligenceRequestType.MORNING_BRIEFING
)

/**
 * A scheduled temporal block or recommendation for the user's day.
 *
 * @property id Unique identifier.
 * @property title Concise title or activity description.
 * @property startTime Start time in milliseconds.
 * @property endTime End time in milliseconds.
 * @property location Optional location or context (e.g., "Outdoors", "Studio").
 * @property isDeepWork Whether this block is dedicated to uninterrupted deep cognitive focus.
 */
@Serializable
data class ScheduleBlock(
    val id: String,
    val title: String,
    val startTime: Long,
    val endTime: Long,
    val location: String = "",
    val isDeepWork: Boolean = false
)

